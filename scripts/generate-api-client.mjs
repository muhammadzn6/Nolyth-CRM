import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const spec = fs.readFileSync(path.join(root, "docs/openapi/orbit.yaml"), "utf8");
const paths = [...spec.matchAll(/^  (\/[^:]+):/gm)].map((match) => match[1]);
if (paths.length === 0) throw new Error("OpenAPI document contains no paths");

const routeFile = path.join(root, "packages/api-client/src/routes.generated.ts");
const routeSource = `// Generated by scripts/generate-api-client.mjs. Do not edit directly.\nexport const ORBIT_DOCUMENTED_ROUTES = ${JSON.stringify(paths, null, 2)} as const;\n`;
fs.writeFileSync(routeFile, routeSource);

const generated = fs.readFileSync(path.join(root, "packages/api-client/src/generated.ts"), "utf8");
const missing = paths.filter((route) => !generated.includes(`path: "${route}"`));
if (missing.length > 0) throw new Error(`Generated client is missing documented routes: ${missing.join(", ")}`);
console.log(`api-client-valid routes=${paths.length}`);
